"""Generate docs/metric-examples.md: one worked example per live metric (WT-10).

Each example is the verbatim output of `glint metrics <TICKER> --explain <id> --db <build>`, so no
number in the file is typed by hand. The ticker is picked by rule, not by hand: the first SPEC
Appendix D ticker whose snapshot has a value for the metric.

Needs a real build, so `make docs` doesn't run it. Run by hand after a refresh:

    cd engine && uv run python scripts/gen_metric_examples.py --db ../data/builds/<build_id>.duckdb
"""

import argparse
import os
import sys
from pathlib import Path

os.environ["COLUMNS"] = "110"  # rich reads this when it isn't writing to a terminal
os.environ["NO_COLOR"] = "1"

import duckdb
from typer.testing import CliRunner

from glint.api.build import connect_read_only
from glint.cli import app
from glint.contracts.metrics import load_registry
from glint.core.settings import REPO_ROOT

# SPEC Appendix D, in table order (multi-class companies by their first-listed class).
APPENDIX_D = [
    "AAPL", "MSFT", "NVDA", "KO", "MU", "KHC", "RIVN", "SBUX", "XOM", "F", "JPM", "O", "BRK.B",
    "GOOGL", "TSM", "ASML",
]  # fmt: skip
OUT = REPO_ROOT / "docs" / "metric-examples.md"


def pick_ticker(con: duckdb.DuckDBPyConnection, metric_id: str) -> str | None:
    for t in APPENDIX_D:
        row = con.execute(
            f"SELECT {metric_id} FROM metrics_snapshot WHERE ticker = ?", [t]
        ).fetchone()
        if row is not None and row[0] is not None:
            return t
    return None


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate docs/metric-examples.md from a real build.")
    ap.add_argument("--db", type=Path, required=True, help="a real build's DuckDB file")
    args = ap.parse_args()
    db = args.db.resolve()
    reg = load_registry()
    runner = CliRunner()
    with connect_read_only(db) as con:
        build = dict(con.execute("SELECT key, value FROM build_meta").fetchall())
        if str(build.get("synthetic", "")).lower() == "true":
            print("refusing: synthetic build", file=sys.stderr)
            return 1
        picks = {m.id: pick_ticker(con, m.id) for m in reg.live()}
    lines = [
        "# Metric worked examples",
        "",
        "<!-- GENERATED by engine/scripts/gen_metric_examples.py. Do not edit by hand. -->",
        "",
        f"> **Snapshot, not current data.** Build `{build['build_id']}`, built "
        f"{str(build['created_at'])[:10]}: fundamentals from the SEC bulk file of "
        f"{str(build['as_of_fundamentals'])[:10]}, prices as of {build['as_of_prices']}. "
        "These numbers illustrate how each metric is computed. They are not today's values.",
        "",
        "Each block is the verbatim output of "
        "`glint metrics <TICKER> --explain <id>` on that build: the formula, every input with its "
        "period and source (XBRL tag and accession, or the price date), and the result. The ticker "
        "is the first SPEC Appendix D company with a value for the metric. Definitions, "
        '"tells you" and "misleads when" are in [metrics.md](metrics.md).',
        "",
    ]
    failures: list[str] = []
    for m in reg.live():
        lines += [f"## `{m.id}` · {m.name}", ""]
        ticker = picks[m.id]
        if ticker is None:
            lines += ["No Appendix D company has a value for this metric in this build.", ""]
            continue
        r = runner.invoke(app, ["metrics", ticker, "--explain", m.id, "--db", str(db)])
        if r.exit_code != 0:
            failures.append(f"{m.id} ({ticker}): exit {r.exit_code}")
            continue
        lines += ["```text", r.output.rstrip(), "```", ""]
    if failures:
        print("explain failed for: " + "; ".join(failures), file=sys.stderr)
        return 1
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(picks)} metrics)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
