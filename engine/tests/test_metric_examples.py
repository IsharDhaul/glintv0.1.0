"""WT-10: docs/metric-examples.md (generated from a real build) has a worked example for every
live metric, and says which build it came from. Reads the committed doc only: no real data."""

import re

from glint.contracts.metrics import load_registry
from glint.core.settings import REPO_ROOT

DOC = REPO_ROOT / "docs" / "metric-examples.md"


def test_every_live_metric_has_a_generated_example() -> None:
    text = DOC.read_text()
    sections = dict(re.findall(r"^## `(\w+)` · .+?\n\n(.*?)(?=^## |\Z)", text, re.M | re.S))
    for m in load_registry().live():
        assert m.id in sections, f"{m.id}: no example section"
        assert "```text" in sections[m.id] and "Result:" in sections[m.id], f"{m.id}: no example"


def test_examples_say_which_build_they_come_from() -> None:
    head = DOC.read_text()[:1000]
    assert "GENERATED by engine/scripts/gen_metric_examples.py" in head
    assert re.search(r"Build `\d{8}T\d{6}Z`, built \d{4}-\d{2}-\d{2}", head)
    assert "not today's values" in head
